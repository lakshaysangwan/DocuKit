/**
 * Pins the Image to PDF page geometry as it was BEFORE it was extracted into
 * src/lib/images-to-pdf-layout.ts.
 *
 * It does not re-implement anything: it takes the geometry lines out of
 * `imagesToPdf()` in src/workers/pdf-worker.ts at commit 78df07e (the last
 * commit where they were inline), runs them, and writes the numbers to
 * src/lib/images-to-pdf-layout.pinned.ts. images-to-pdf-layout.test.ts then
 * holds the extracted function to those numbers, so the refactor provably
 * changed no output.
 *
 *   node scripts/pin-images-to-pdf-layout.mjs
 *
 * Only needs re-running if the table's inputs below are changed; the source it
 * reads is fixed by the commit hash.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import ts from 'typescript';

const COMMIT = '78df07e';
const source = execFileSync('git', ['show', `${COMMIT}:src/workers/pdf-worker.ts`], { encoding: 'utf8' })
  .replace(/\r\n/g, '\n');

const between = (from, to) => {
  const start = source.indexOf(from);
  const end = source.indexOf(to, start);
  if (start === -1 || end === -1) throw new Error(`could not find "${from}" … "${to}"`);
  return source.slice(start, end);
};

// The page-size table, then everything from "let pageW" down to the draw call.
const sizes = between('  const PAGE_SIZES: Record<string, [number, number]> = {', '  const total = buffers.length;');
const geometry = between('    let pageW: number;', '    if (options.backgroundColor) {');

const program = `
  (function legacy(imgW, imgH, options) {
    const doc = { addPage() { return {}; } };
    ${sizes}
    ${geometry}
    return { pageW, pageH, draw: { x: drawX, y: drawY, w: drawW, h: drawH } };
  })
`;
const legacy = (0, eval)(ts.transpileModule(program, { compilerOptions: { target: 'ES2020' } }).outputText);

const IMAGES = [
  { name: 'portrait', width: 900, height: 1200 },
  { name: 'landscape', width: 1200, height: 800 },
];
const MARGINS = [
  // The tool's default: 10 mm, rounded to two decimals as the island sends it.
  { top: 28.35, right: 28.35, bottom: 28.35, left: 28.35 },
  // Uneven, so a swapped side or axis cannot cancel out.
  { top: 72, right: 36, bottom: 18, left: 108 },
];
const PAGE_SIZES = ['fit', 'a4', 'letter', 'legal', 'custom'];
const PLACEMENTS = ['center', 'fit', 'stretch', 'cover'];

const rows = [];
for (const pageSize of PAGE_SIZES) {
  for (const placement of PLACEMENTS) {
    for (const img of IMAGES) {
      for (const margins of MARGINS) {
        const options = {
          pageSize,
          placement,
          margins,
          backgroundColor: '#FFFFFF',
          ...(pageSize === 'custom' ? { customWidth: 420, customHeight: 300 } : {}),
        };
        rows.push({ img: { width: img.width, height: img.height }, options, expected: legacy(img.width, img.height, options) });
      }
    }
  }
}

const out = `/**
 * GENERATED by scripts/pin-images-to-pdf-layout.mjs — do not edit by hand.
 *
 * The page size and draw rectangle Image to PDF produced for each case at
 * commit ${COMMIT}, computed by running the geometry lines of that commit's
 * \`imagesToPdf()\` as they stood. Points, bottom-left origin.
 */
import type { ImagesToPdfOptions } from '../types/worker-messages';

export interface PinnedLayout {
  img: { width: number; height: number };
  options: ImagesToPdfOptions;
  expected: { pageW: number; pageH: number; draw: { x: number; y: number; w: number; h: number } };
}

export const PINNED_LAYOUTS: PinnedLayout[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;
writeFileSync(new URL('../src/lib/images-to-pdf-layout.pinned.ts', import.meta.url), out);
console.log(`pinned ${rows.length} layouts from ${COMMIT}`);
