/**
 * The standard PDF fonts the tools write with, and how wide a line of text is
 * in each.
 *
 * Text written with a standard font embeds no font file, so its width on the
 * page is fixed by the font's published metrics rather than by whatever font
 * the browser has. A preview that sizes text from these same numbers draws the
 * box that is written to the file. Watermark PDF uses the bold three, Add Page
 * Numbers the regular three.
 *
 * The standard fonts can only draw the WinAnsi (Western European) characters;
 * `unsupportedChars` lists what a text uses outside that set, so a tool can
 * say so before anything is written.
 *
 * Generated from pdf-lib's own copies of Adobe's AFM files; unit tests check
 * every width against pdf-lib.
 *
 * Pure: no DOM, no pdf-lib.
 */

